"""Create fictitious retail data to exercise all four dashboard views."""
import json
from pathlib import Path
import numpy as np
import pandas as pd


def make_demo():
    rng = np.random.default_rng(2026)
    dates = pd.date_range('2025-01-01', '2025-01-31').union(pd.date_range('2025-03-01', '2025-03-31')).union(pd.date_range('2026-01-01', '2026-01-31'))
    rows = []
    stores = [(1, 'Example North', 'Demo City A', 'A'), (2, 'Example North', 'Demo City B', 'B'),
              (3, 'Example South', 'Demo City C', 'A'), (4, 'Example South', 'Demo City D', 'B')]
    for date in dates:
        oil = float(60 + 10 * np.sin(date.dayofyear / 17)) if date.day % 7 else np.nan
        for store, state, city, store_type in stores:
            transactions = int(rng.integers(50, 160))
            for family in ['Bread', 'Dairy', 'Fruit']:
                promotion = int(rng.choice([0, 0, 0, 2, 5]))
                sales = max(0., float(rng.normal(100 + 7 * store + 3 * promotion, 20)))
                if date.year == 2026:
                    sales *= 1.08
                rows.append({'date': date.date(), 'store_nbr': store, 'family': family, 'state': state,
                             'city': city, 'store_type': store_type, 'sales': round(sales, 2),
                             'transactions': transactions, 'onpromotion': promotion, 'dcoilwtico': oil})
    return pd.DataFrame(rows)


if __name__ == '__main__':
    directory = Path(__file__).parent / 'data'
    directory.mkdir(exist_ok=True)
    make_demo().to_csv(directory / 'synthetic_sales.csv', index=False)
    (directory / 'synthetic_metadata.json').write_text(json.dumps({
        'synthetic': True, 'source': 'Fictitious fixture generated by make_demo_data.py; seed 2026',
        'sales_unit': 'synthetic sales units', 'oil_unit': 'synthetic oil index',
        'transactions_grain': 'date_store'}, indent=2))
    print('Generated 1,116 fictitious rows; no real retailer records are included.')
